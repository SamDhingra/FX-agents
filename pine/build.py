def build() -> list[str]:
    out = []
    for name, d in SCRIPTS.items():
        txt = HEAD.format(title=d["title"], about=d["about"]) + COMMON_INPUTS.format(rr=d["rr"], hold=d["hold"], windows=d["windows"]) \
            + d["code"] + FOOTER
        (HERE / f"{name}.pine").write_text(txt)
        out.append(name)
    return out


if __name__ == "__main__":
    print("wrote", ", ".join(build()))

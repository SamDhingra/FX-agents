"""Builds the TradingView Pine v5 scripts for the FX-Agents setups (python pine/build.py).

Each script = header + the setup's own signal code + the bot's shared trade management, so every script
manages trades the same way the bot does (1R partial + trailing runner, or a fixed TP, NY entry windows,
15:50 flatten, max hold, the 1h trend filter standing in for the bot's bias rule). Bands, EMAs and
higher-timeframe values only use CLOSED candles, so nothing repaints.
"""
from pathlib import Path

HERE = Path(__file__).parent

HEAD = '''//@version=5
// FX-Agents · {title}
// {about}
// Generated by pine/build.py from the bot's rules. Set Properties → Commission/Slippage to your broker's spread.
strategy("FX-Agents · {title}", overlay=true, initial_capital=100000, default_qty_type=strategy.fixed,
     default_qty_value=1, process_orders_on_close=true, margin_long=0, margin_short=0)
'''

COMMON_INPUTS = '''
// ── the bot's trade management inputs ────────────────────────────────────────────────────────
exitMode   = input.string("Bot (1R partial + trail)", "Exit", options=["Bot (1R partial + trail)", "Fixed TP"], group="Management")
rr         = input.float({rr}, "First target / TP (R)", step=0.25, group="Management")
partialPct = input.float(50, "Bank at first target (%)", group="Management")
lockR      = input.float(0.1, "Stop after first target (+R)", group="Management")
trailStep  = input.float(1.0, "Trail step (R)", group="Management")
maxHoldMin = input.int({hold}, "Max hold (minutes)", group="Management")
windows    = input.string("{windows}", "Entry windows (New York)", group="Management")
flatHm     = input.int(1550, "Flatten at (HHMM, New York)", group="Management")
useBias    = input.bool(true, "Only with the 1h trend (EMA20/50 on closed 1h bars)", group="Management")

nyHm  = hour(time, "America/New_York") * 100 + minute(time, "America/New_York")
inWin = not na(time(timeframe.period, windows, "America/New_York")) and not (nyHm >= flatHm - 20 and nyHm < 1700)
htfC  = request.security(syminfo.tickerid, "60", close[1], lookahead=barmerge.lookahead_on)
htfF  = request.security(syminfo.tickerid, "60", ta.ema(close, 20)[1], lookahead=barmerge.lookahead_on)
htfS  = request.security(syminfo.tickerid, "60", ta.ema(close, 50)[1], lookahead=barmerge.lookahead_on)
biasUp = not useBias or (htfF > htfS and htfC > htfS)
biasDn = not useBias or (htfF < htfS and htfC < htfS)
atr14 = ta.atr(14)

var float eP = na
var float rP = na
var float stopNow = na
var int   stepN = 0
var int   entryTime = na
goLong = false
goShort = false
stopL = float(na)
stopS = float(na)
'''

FOOTER = '''
// ── entries & the bot's management ────────────────────────────────────────────────────────────
flat = strategy.position_size == 0
if flat and inWin and goLong and biasUp and not na(stopL) and close > stopL
    eP := close
    rP := close - stopL
    stopNow := stopL
    stepN := 0
    entryTime := time
    strategy.entry("L", strategy.long)
else if flat and inWin and goShort and biasDn and not na(stopS) and close < stopS
    eP := close
    rP := stopS - close
    stopNow := stopS
    stepN := 0
    entryTime := time
    strategy.entry("S", strategy.short)

dir = strategy.position_size > 0 ? 1 : strategy.position_size < 0 ? -1 : 0
if dir != 0 and exitMode == "Bot (1R partial + trail)"
    best = dir > 0 ? high : low
    while (best - (eP + dir * (rr + stepN * trailStep) * rP)) * dir >= 0 and stepN < 50
        stepN += 1
        newStop = stepN == 1 ? eP + dir * lockR * rP : eP + dir * (rr + (stepN - 2) * trailStep) * rP
        if (newStop - stopNow) * dir > 0
            stopNow := newStop

if exitMode == "Fixed TP"
    strategy.exit("TP L", "L", limit=eP + rr * rP, stop=stopNow)
    strategy.exit("TP S", "S", limit=eP - rr * rP, stop=stopNow)
else
    strategy.exit("Partial L", "L", qty_percent=partialPct, limit=eP + rr * rP, stop=stopNow)
    strategy.exit("Runner L", "L", stop=stopNow)
    strategy.exit("Partial S", "S", qty_percent=partialPct, limit=eP - rr * rP, stop=stopNow)
    strategy.exit("Runner S", "S", stop=stopNow)

if dir != 0 and not na(entryTime) and time - entryTime >= maxHoldMin * 60000
    strategy.close_all("max hold")
if nyHm >= flatHm and nyHm < 1700
    strategy.close_all("15:50 flatten")
plot(dir != 0 ? stopNow : na, "Stop", color.new(color.red, 0), style=plot.style_linebr)
'''

